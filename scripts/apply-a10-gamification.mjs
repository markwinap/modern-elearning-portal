import "dotenv/config";
import postgres from "postgres";

const databaseUrl = process.env.DATABASE_URL;
if (!databaseUrl) {
  console.error("DATABASE_URL is not set");
  process.exit(1);
}

const sql = postgres(databaseUrl);

const statements = [
  // Reset existing A10 tables so the script is idempotent across schema tweaks.
  `DROP TABLE IF EXISTS "pg-drizzle_leaderboard_snapshot" CASCADE;`,
  `DROP TABLE IF EXISTS "pg-drizzle_user_streak" CASCADE;`,
  `DROP TABLE IF EXISTS "pg-drizzle_user_level" CASCADE;`,
  `DROP TABLE IF EXISTS "pg-drizzle_user_badge" CASCADE;`,
  `DROP TABLE IF EXISTS "pg-drizzle_badge_definition" CASCADE;`,
  `DROP TABLE IF EXISTS "pg-drizzle_points_ledger" CASCADE;`,
  `DROP TABLE IF EXISTS "pg-drizzle_gamification_config" CASCADE;`,
  `DROP TYPE IF EXISTS "leaderboard_scope";`,
  `DROP TYPE IF EXISTS "gamification_badge_criteria";`,
  `DROP TYPE IF EXISTS "gamification_event_source";`,
  // Enums
  `CREATE TYPE "gamification_event_source" AS ENUM(
    'activity_completed', 'quiz_passed', 'course_completed', 'daily_login', 'badge_bonus'
  );`,
  `CREATE TYPE "gamification_badge_criteria" AS ENUM(
    'points_threshold', 'activity_count', 'quiz_count', 'course_count', 'streak_days'
  );`,
  `CREATE TYPE "leaderboard_scope" AS ENUM('global', 'course');`,

  // Gamification config
  `CREATE TABLE IF NOT EXISTS "pg-drizzle_gamification_config" (
    "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "activityCompletedPoints" integer DEFAULT 10 NOT NULL,
    "quizPassedPoints" integer DEFAULT 25 NOT NULL,
    "courseCompletedPoints" integer DEFAULT 100 NOT NULL,
    "dailyLoginPoints" integer DEFAULT 5 NOT NULL,
    "levelThresholds" jsonb DEFAULT '[0,100,250,500,1000,2000]'::jsonb NOT NULL,
    "createdAt" timestamp with time zone DEFAULT now() NOT NULL,
    "updatedAt" timestamp with time zone
  );`,

  // Points ledger
  `CREATE TABLE IF NOT EXISTS "pg-drizzle_points_ledger" (
    "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "userId" text NOT NULL REFERENCES "user"("id") ON DELETE cascade,
    "amount" integer NOT NULL,
    "source_type" "gamification_event_source" NOT NULL,
    "sourceId" text NOT NULL,
    "courseId" integer REFERENCES "pg-drizzle_course"("id") ON DELETE cascade,
    "reason" text,
    "createdAt" timestamp with time zone DEFAULT now() NOT NULL
  );`,

  // Badge definitions
  `CREATE TABLE IF NOT EXISTS "pg-drizzle_badge_definition" (
    "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "key" varchar(64) NOT NULL,
    "name" varchar(128) NOT NULL,
    "description" text,
    "icon" varchar(64),
    "criteria_type" "gamification_badge_criteria" NOT NULL,
    "criteriaValue" jsonb DEFAULT '{}'::jsonb NOT NULL
  );`,

  // User badges
  `CREATE TABLE IF NOT EXISTS "pg-drizzle_user_badge" (
    "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "userId" text NOT NULL REFERENCES "user"("id") ON DELETE cascade,
    "badgeId" integer NOT NULL REFERENCES "pg-drizzle_badge_definition"("id") ON DELETE cascade,
    "awardedAt" timestamp with time zone DEFAULT now() NOT NULL
  );`,

  // User levels
  `CREATE TABLE IF NOT EXISTS "pg-drizzle_user_level" (
    "userId" text PRIMARY KEY NOT NULL REFERENCES "user"("id") ON DELETE cascade,
    "totalPoints" integer DEFAULT 0 NOT NULL,
    "level" integer DEFAULT 1 NOT NULL,
    "updatedAt" timestamp with time zone
  );`,

  // User streaks
  `CREATE TABLE IF NOT EXISTS "pg-drizzle_user_streak" (
    "userId" text PRIMARY KEY NOT NULL REFERENCES "user"("id") ON DELETE cascade,
    "currentStreak" integer DEFAULT 0 NOT NULL,
    "longestStreak" integer DEFAULT 0 NOT NULL,
    "lastActivityDate" date
  );`,

  // Leaderboard snapshots
  `CREATE TABLE IF NOT EXISTS "pg-drizzle_leaderboard_snapshot" (
    "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "scope" "leaderboard_scope" NOT NULL,
    "courseId" integer REFERENCES "pg-drizzle_course"("id") ON DELETE cascade,
    "period" varchar(32) DEFAULT 'allTime' NOT NULL,
    "entries" jsonb DEFAULT '[]'::jsonb NOT NULL,
    "calculatedAt" timestamp with time zone DEFAULT now() NOT NULL
  );`,

  // Unique constraints via indexes
  `CREATE UNIQUE INDEX IF NOT EXISTS "badge_definition_key_unique"
    ON "pg-drizzle_badge_definition"("key");`,
  `CREATE UNIQUE INDEX IF NOT EXISTS "points_ledger_user_source"
    ON "pg-drizzle_points_ledger"("userId", "source_type", "sourceId");`,
  `CREATE UNIQUE INDEX IF NOT EXISTS "user_badge_user_badge"
    ON "pg-drizzle_user_badge"("userId", "badgeId");`,
  `CREATE UNIQUE INDEX IF NOT EXISTS "leaderboard_snapshot_scope_course_period"
    ON "pg-drizzle_leaderboard_snapshot"("scope", "courseId", "period");`,

  // Other indexes
  `CREATE INDEX IF NOT EXISTS "gamification_config_created_idx"
    ON "pg-drizzle_gamification_config"("createdAt");`,
  `CREATE INDEX IF NOT EXISTS "points_ledger_user_created_idx"
    ON "pg-drizzle_points_ledger"("userId", "createdAt");`,
  `CREATE INDEX IF NOT EXISTS "badge_definition_key_idx"
    ON "pg-drizzle_badge_definition"("key");`,
  `CREATE INDEX IF NOT EXISTS "user_badge_user_idx"
    ON "pg-drizzle_user_badge"("userId");`,
  `CREATE INDEX IF NOT EXISTS "leaderboard_snapshot_scope_course_idx"
    ON "pg-drizzle_leaderboard_snapshot"("scope", "courseId");`,
];

async function main() {
  for (const statement of statements) {
    try {
      await sql.unsafe(statement);
      console.log("Executed:", statement.split("\n")[0].trim());
    } catch (error) {
      console.error(
        "Failed to execute statement:",
        statement.split("\n")[0].trim(),
      );
      console.error(error);
      process.exitCode = 1;
      break;
    }
  }
  await sql.end();
}

await main();
